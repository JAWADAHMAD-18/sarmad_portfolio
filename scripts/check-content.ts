import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { contentSchema, type Content } from "../lib/schema";
import { sectionStatuses } from "../lib/visibility";

const root = process.cwd();
const contentPath = path.join(root, "docs", "content.json");
const statusPath = path.join(root, "docs", "STATUS.generated.md");

const REQUIRED_PATHS = [
  "meta.name",
  "meta.title",
  "hero.headline",
  "hero.subheadline",
] as const;

function collectNulls(value: unknown, currentPath: string, out: string[]) {
  if (value === null) {
    out.push(currentPath);
    return;
  }
  if (Array.isArray(value)) {
    value.forEach((item, index) => {
      collectNulls(item, `${currentPath}[${index}]`, out);
    });
    return;
  }
  if (!value || typeof value !== "object") return;
  for (const [key, child] of Object.entries(value)) {
    if (currentPath === "" && key === "_readme") continue;
    const next = currentPath ? `${currentPath}.${key}` : key;
    collectNulls(child, next, out);
  }
}

function collectDrafts(value: unknown, currentPath: string, out: string[]) {
  if (Array.isArray(value)) {
    value.forEach((item, index) => {
      collectDrafts(item, `${currentPath}[${index}]`, out);
    });
    return;
  }
  if (!value || typeof value !== "object") return;
  const record = value as Record<string, unknown>;
  if (record.needsApproval === true) out.push(currentPath);
  for (const [key, child] of Object.entries(record)) {
    if (key === "needsApproval") continue;
    if (currentPath === "" && key === "_readme") continue;
    const next = currentPath ? `${currentPath}.${key}` : key;
    collectDrafts(child, next, out);
  }
}

function valueAt(source: unknown, dotted: string): unknown {
  return dotted.split(".").reduce<unknown>((current, key) => {
    if (!current || typeof current !== "object") return undefined;
    return (current as Record<string, unknown>)[key];
  }, source);
}

function privateLines(content: Content): string[] {
  const lines: string[] = [];
  if (!content.contact.phone.public) {
    lines.push("- `contact.phone` (public is false)");
  }
  if (!content.contact.whatsapp.public) {
    lines.push("- `contact.whatsapp` (public is false)");
  }
  if (!content.acca.membershipNumberPublic) {
    lines.push("- `acca.membershipNumber` (membershipNumberPublic is false)");
  }
  return lines;
}

function secrets(content: Content): string[] {
  const values: string[] = [];
  if (!content.contact.phone.public && content.contact.phone.value) {
    values.push(content.contact.phone.value);
  }
  if (!content.contact.whatsapp.public && content.contact.whatsapp.value) {
    values.push(content.contact.whatsapp.value);
  }
  if (!content.acca.membershipNumberPublic && content.acca.membershipNumber) {
    values.push(content.acca.membershipNumber);
  }
  return values;
}

function buildReport(content: Content, raw: unknown): string {
  const sections = sectionStatuses(content);
  const nulls: string[] = [];
  collectNulls(raw, "", nulls);
  const drafts: string[] = [];
  collectDrafts(raw, "", drafts);
  const on = sections.filter((section) => section.state === "ON").length;
  const off = sections.length - on;
  const notes: string[] = [];
  if (content.contact.email.temporary) {
    notes.push("- `contact.email.temporary` is true");
  }

  const sectionRows = sections
    .map(
      (section) =>
        `| ${section.id} | ${section.state} | ${section.reason} |`,
    )
    .join("\n");

  const nullList = nulls.length
    ? nulls.map((item) => `- \`${item}\``).join("\n")
    : "- None";
  const draftList = drafts.length
    ? drafts.map((item) => `- \`${item}\``).join("\n")
    : "- None";
  const privateList = privateLines(content).join("\n") || "- None";
  const noteList = notes.length ? notes.join("\n") : "- None";

  return `# Content status

Generated by \`npm run check\`. Do not edit by hand.

## Sections

| Section | State | Why |
| --- | --- | --- |
${sectionRows}

## Null fields

${nullList}

## Needs approval

${draftList}

## Private

These values are omitted from this report and from the client bundle.

${privateList}

## Notes

${noteList}

## Summary

- Sections on: ${on}
- Sections off: ${off}
- Null fields: ${nulls.length}
- Needs approval: ${drafts.length}

Strict mode (\`--strict\`) fails when a visible section is missing its minimum data, when \`meta.name\`, \`meta.title\`, \`hero.headline\`, or \`hero.subheadline\` is null, or when any item has \`needsApproval: true\`. Other null fields are listed above and do not fail the check.
`;
}

function main() {
  const strict = process.argv.includes("--strict");
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(contentPath, "utf8")) as unknown;
  } catch (error) {
    const message = error instanceof Error ? error.message : "Unknown error";
    console.error(`Could not read docs/content.json\n${message}`);
    process.exit(1);
  }

  const parsed = contentSchema.safeParse(raw);
  if (!parsed.success) {
    const details = parsed.error.issues
      .map((issue) => `${issue.path.join(".") || "(root)"}: ${issue.message}`)
      .join("\n");
    console.error(`content.json failed validation:\n${details}`);
    process.exit(1);
  }

  const report = buildReport(parsed.data, raw);
  for (const secret of secrets(parsed.data)) {
    if (report.includes(secret)) {
      console.error(
        "Refusing to write the status report because it contains a private value.",
      );
      process.exit(1);
    }
  }

  writeFileSync(statusPath, report, "utf8");
  process.stdout.write(report);

  const nulls: string[] = [];
  collectNulls(raw, "", nulls);
  const missingMinimum = sectionStatuses(parsed.data).filter((section) =>
    section.reason.startsWith("missing"),
  );
  const requiredNulls = REQUIRED_PATHS.filter((item) => {
    const value = valueAt(raw, item);
    return value == null || value === "";
  });

  const drafts: string[] = [];
  collectDrafts(raw, "", drafts);

  if (
    strict &&
    (missingMinimum.length > 0 || requiredNulls.length > 0 || drafts.length > 0)
  ) {
    process.exit(1);
  }
}

main();
